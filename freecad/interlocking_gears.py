"""
Interlocking Gears Script for FreeCAD

This script creates two interlocking gears where a smaller pinion gear fits 
inside a larger internal (ring) gear and they rotate together.

The internal gear has teeth on the inside, and the pinion gear meshes with it
from within. When the pinion rotates, it drives the internal gear to rotate
in the same direction (unlike external gears which rotate in opposite directions).

Usage:
    1. Open FreeCAD
    2. Go to View -> Panels -> Python console
    3. Load this script using: exec(open("path/to/interlocking_gears.py").read())
    OR
    4. Copy and paste the content into FreeCAD's Python console

Parameters can be adjusted below to match your gear dimensions.
"""

import math

# Try to import FreeCAD modules
try:
    import FreeCAD as App
    import Part
    from FreeCAD import Base
    FREECAD_AVAILABLE = True
except ImportError:
    FREECAD_AVAILABLE = False
    print("FreeCAD modules not available. Running in standalone mode for testing.")


# ============================================================================
# GEAR PARAMETERS - Adjust these values to match your gears
# ============================================================================

# Module (must be the same for both gears to mesh properly)
# The module is the ratio of pitch diameter to number of teeth
MODULE = 2.0  # mm

# Number of teeth on the internal (ring) gear
INTERNAL_GEAR_TEETH = 40

# Number of teeth on the pinion (small external gear)
PINION_TEETH = 15

# Pressure angle (standard values: 14.5°, 20°, or 25°)
PRESSURE_ANGLE = 20.0  # degrees

# Gear thickness (height/width of the gear)
GEAR_THICKNESS = 10.0  # mm

# Addendum coefficient (typically 1.0 for standard gears)
ADDENDUM_COEF = 1.0

# Dedendum coefficient (typically 1.25 for standard gears)
DEDENDUM_COEF = 1.25

# Ring gear outer diameter addition (wall thickness outside the teeth)
RING_WALL_THICKNESS = 5.0  # mm


# ============================================================================
# GEAR CALCULATION FUNCTIONS
# ============================================================================

def calculate_gear_dimensions(module, teeth, pressure_angle_deg, addendum_coef, dedendum_coef):
    """
    Calculate the basic dimensions for a gear.
    
    Returns a dictionary with:
    - pitch_diameter: The theoretical diameter where gears mesh
    - base_diameter: The diameter of the base circle for involute generation
    - addendum: Height of tooth above pitch circle
    - dedendum: Depth of tooth below pitch circle
    - outer_diameter: Overall diameter for external gears
    - root_diameter: Diameter at the base of teeth
    """
    pressure_angle_rad = math.radians(pressure_angle_deg)
    
    pitch_diameter = module * teeth
    base_diameter = pitch_diameter * math.cos(pressure_angle_rad)
    addendum = addendum_coef * module
    dedendum = dedendum_coef * module
    outer_diameter = pitch_diameter + 2 * addendum
    root_diameter = pitch_diameter - 2 * dedendum
    
    return {
        'pitch_diameter': pitch_diameter,
        'base_diameter': base_diameter,
        'addendum': addendum,
        'dedendum': dedendum,
        'outer_diameter': outer_diameter,
        'root_diameter': root_diameter,
        'module': module,
        'teeth': teeth,
        'pressure_angle': pressure_angle_deg
    }


def calculate_center_distance(module, internal_teeth, pinion_teeth):
    """
    Calculate the center distance between internal gear and pinion.
    
    For internal gears: center_distance = module * (internal_teeth - pinion_teeth) / 2
    """
    return module * (internal_teeth - pinion_teeth) / 2


def involute_point(base_radius, angle):
    """
    Calculate a point on an involute curve.
    
    The involute is generated by unwrapping a string from the base circle.
    """
    x = base_radius * (math.cos(angle) + angle * math.sin(angle))
    y = base_radius * (math.sin(angle) - angle * math.cos(angle))
    return (x, y)


def generate_involute_points(base_radius, start_angle, end_angle, num_points=20):
    """
    Generate a series of points along an involute curve.
    
    Note: This function is provided for reference and can be used for 
    creating more detailed gear profiles in future enhancements.
    """
    if num_points < 2:
        num_points = 2  # Minimum 2 points to avoid division by zero
    if base_radius <= 0:
        raise ValueError("base_radius must be positive")
    
    points = []
    for i in range(num_points):
        t = start_angle + (end_angle - start_angle) * i / (num_points - 1)
        x, y = involute_point(base_radius, t)
        points.append(Base.Vector(x, y, 0))
    return points


def create_gear_profile_external(dims, num_points_per_tooth=20):
    """
    Create the 2D profile of an external gear (pinion).
    Returns a list of points forming the gear profile.
    
    Note: This function is provided for reference and can be used for 
    creating more detailed gear profiles with proper involute curves.
    """
    teeth = dims['teeth']
    if teeth <= 0:
        raise ValueError("Number of teeth must be positive")
    if num_points_per_tooth < 2:
        num_points_per_tooth = 2  # Minimum 2 points to avoid division by zero
    
    pitch_radius = dims['pitch_diameter'] / 2
    base_radius = dims['base_diameter'] / 2
    outer_radius = dims['outer_diameter'] / 2
    root_radius = dims['root_diameter'] / 2
    pressure_angle_rad = math.radians(dims['pressure_angle'])
    
    if base_radius <= 0:
        raise ValueError("Base radius must be positive")
    
    # Angular pitch (angle between teeth)
    angular_pitch = 2 * math.pi / teeth
    
    # Tooth thickness at pitch circle (for standard gears, half the circular pitch)
    tooth_thickness_angle = angular_pitch / 2
    
    points = []
    
    for i in range(teeth):
        tooth_center_angle = i * angular_pitch
        
        # Generate the involute for the right side of the tooth
        # Calculate involute parameters
        inv_start = 0
        inv_end = math.sqrt((outer_radius / base_radius) ** 2 - 1) if outer_radius > base_radius else 0.5
        
        # Right flank (involute)
        right_points = []
        for j in range(num_points_per_tooth):
            t = inv_start + (inv_end - inv_start) * j / (num_points_per_tooth - 1)
            x, y = involute_point(base_radius, t)
            # Rotate to tooth position
            angle = tooth_center_angle + tooth_thickness_angle / 4
            rx = x * math.cos(angle) - y * math.sin(angle)
            ry = x * math.sin(angle) + y * math.cos(angle)
            right_points.append(Base.Vector(rx, ry, 0))
        
        # Left flank (mirrored involute)
        left_points = []
        for j in range(num_points_per_tooth):
            t = inv_start + (inv_end - inv_start) * j / (num_points_per_tooth - 1)
            x, y = involute_point(base_radius, t)
            y = -y  # Mirror
            # Rotate to tooth position
            angle = tooth_center_angle - tooth_thickness_angle / 4
            rx = x * math.cos(angle) - y * math.sin(angle)
            ry = x * math.sin(angle) + y * math.cos(angle)
            left_points.append(Base.Vector(rx, ry, 0))
        left_points.reverse()
        
        # Add points for this tooth
        # Root circle arc
        root_start_angle = tooth_center_angle - angular_pitch / 2 + 0.1
        root_end_angle = tooth_center_angle - tooth_thickness_angle / 4
        for j in range(3):
            a = root_start_angle + (root_end_angle - root_start_angle) * j / 2
            points.append(Base.Vector(root_radius * math.cos(a), root_radius * math.sin(a), 0))
        
        points.extend(left_points)
        
        # Tip arc
        tip_start = tooth_center_angle - tooth_thickness_angle / 4 + inv_end
        tip_end = tooth_center_angle + tooth_thickness_angle / 4 - inv_end
        for j in range(3):
            a = (tip_start + tip_end) / 2
            points.append(Base.Vector(outer_radius * math.cos(a), outer_radius * math.sin(a), 0))
        
        points.extend(right_points)
    
    return points


def create_simplified_gear(name, dims, gear_type='external', thickness=10.0, ring_wall=5.0):
    """
    Create a simplified gear using FreeCAD's Part module.
    
    For simplicity, this creates a gear approximation using circles and cylinders.
    For more accurate involute gears, use FreeCAD's Gear Workbench.
    
    gear_type: 'external' for pinion, 'internal' for ring gear
    """
    if not FREECAD_AVAILABLE:
        print(f"Would create {gear_type} gear '{name}' with {dims['teeth']} teeth")
        return None
    
    if gear_type == 'external':
        # Create external gear (pinion) as a cylinder with approximate tooth profile
        outer_radius = dims['outer_diameter'] / 2
        root_radius = dims['root_diameter'] / 2
        
        # Create main body
        outer_cyl = Part.makeCylinder(outer_radius, thickness)
        
        # Create simplified tooth cuts (for visualization)
        teeth = dims['teeth']
        pitch_radius = dims['pitch_diameter'] / 2
        tooth_depth = dims['addendum'] + dims['dedendum']
        tooth_width = math.pi * dims['module'] / 2
        
        gear_shape = outer_cyl
        
        # Create tooth gaps using boxes
        for i in range(teeth):
            angle = 2 * math.pi * i / teeth
            gap_pos = Base.Vector(
                pitch_radius * math.cos(angle + math.pi / teeth),
                pitch_radius * math.sin(angle + math.pi / teeth),
                0
            )
            # Create a small box for the tooth gap
            gap = Part.makeBox(tooth_width * 0.8, tooth_depth * 1.5, thickness)
            gap.translate(Base.Vector(-tooth_width * 0.4, -tooth_depth * 0.75, 0))
            
            # Rotate and position the gap
            gap.rotate(Base.Vector(0, 0, 0), Base.Vector(0, 0, 1), math.degrees(angle + math.pi / teeth))
            gap.translate(Base.Vector(
                root_radius * math.cos(angle + math.pi / teeth),
                root_radius * math.sin(angle + math.pi / teeth),
                0
            ))
            
            try:
                gear_shape = gear_shape.cut(gap)
            except Exception:
                pass  # Skip if boolean operation fails
        
        # Create the Part feature
        part = App.ActiveDocument.addObject("Part::Feature", name)
        part.Shape = gear_shape
        
    else:  # internal gear
        # Create ring gear with internal teeth
        inner_tooth_radius = dims['outer_diameter'] / 2  # Inner surface where teeth start
        root_radius = dims['root_diameter'] / 2  # Where teeth end (larger for internal)
        outer_radius = inner_tooth_radius + ring_wall
        
        # For internal gears, the geometry is inverted
        # The "outer diameter" is actually the inner tooth tips
        # The "root diameter" is where the tooth bases are (larger radius)
        
        # Create outer ring
        outer_cyl = Part.makeCylinder(dims['root_diameter'] / 2 + ring_wall, thickness)
        inner_cyl = Part.makeCylinder(dims['outer_diameter'] / 2, thickness)
        
        ring = outer_cyl.cut(inner_cyl)
        
        # Add teeth pointing inward by adding material
        teeth = dims['teeth']
        pitch_radius = dims['pitch_diameter'] / 2
        tooth_depth = dims['addendum'] + dims['dedendum']
        tooth_width = math.pi * dims['module'] / 2
        
        for i in range(teeth):
            angle = 2 * math.pi * i / teeth
            # Create tooth as a small block
            tooth = Part.makeBox(tooth_depth, tooth_width * 0.8, thickness)
            tooth.translate(Base.Vector(-tooth_depth / 2, -tooth_width * 0.4, 0))
            
            # Position at the inner radius
            tooth.rotate(Base.Vector(0, 0, 0), Base.Vector(0, 0, 1), math.degrees(angle))
            tooth.translate(Base.Vector(
                pitch_radius * math.cos(angle),
                pitch_radius * math.sin(angle),
                0
            ))
            
            try:
                ring = ring.fuse(tooth)
            except Exception:
                pass
        
        # Clean up the shape
        ring = ring.removeSplitter()
        
        part = App.ActiveDocument.addObject("Part::Feature", name)
        part.Shape = ring
    
    return part


def position_gears(internal_gear, pinion, center_distance):
    """
    Position the pinion inside the internal gear at the correct center distance.
    """
    if not FREECAD_AVAILABLE:
        print(f"Would position pinion at center distance: {center_distance} mm")
        return
    
    # Move the pinion to the correct position
    pinion.Placement.Base = Base.Vector(center_distance, 0, 0)


def create_rotation_animation_link(internal_gear, pinion, internal_teeth, pinion_teeth):
    """
    Create a formula to link the rotation of both gears.
    
    For internal gears, the ratio is: omega_internal / omega_pinion = pinion_teeth / internal_teeth
    Both gears rotate in the SAME direction (unlike external gears).
    
    Returns the gear ratio information for manual animation.
    """
    gear_ratio = pinion_teeth / internal_teeth
    
    print("\n" + "=" * 60)
    print("GEAR ROTATION RELATIONSHIP")
    print("=" * 60)
    print(f"Gear Ratio: {gear_ratio:.4f}")
    print(f"When the pinion rotates 360°, the internal gear rotates {360 * gear_ratio:.2f}°")
    print(f"Both gears rotate in the SAME direction.")
    print("\nTo animate in FreeCAD:")
    print(f"1. If pinion angle = α, then internal gear angle = α × {gear_ratio:.4f}")
    print("2. You can use Spreadsheet workbench to link rotations")
    print("=" * 60 + "\n")
    
    return gear_ratio


def main():
    """
    Main function to create the interlocking gear assembly.
    """
    print("\n" + "=" * 60)
    print("INTERLOCKING GEARS GENERATOR")
    print("=" * 60)
    
    # Calculate dimensions
    internal_dims = calculate_gear_dimensions(
        MODULE, INTERNAL_GEAR_TEETH, PRESSURE_ANGLE, ADDENDUM_COEF, DEDENDUM_COEF
    )
    
    pinion_dims = calculate_gear_dimensions(
        MODULE, PINION_TEETH, PRESSURE_ANGLE, ADDENDUM_COEF, DEDENDUM_COEF
    )
    
    center_distance = calculate_center_distance(MODULE, INTERNAL_GEAR_TEETH, PINION_TEETH)
    
    # Print calculated values
    print(f"\nInternal (Ring) Gear:")
    print(f"  - Teeth: {INTERNAL_GEAR_TEETH}")
    print(f"  - Pitch Diameter: {internal_dims['pitch_diameter']:.2f} mm")
    print(f"  - Outer Diameter (tooth tips): {internal_dims['outer_diameter']:.2f} mm")
    print(f"  - Root Diameter (tooth bases): {internal_dims['root_diameter']:.2f} mm")
    
    print(f"\nPinion (Small Gear):")
    print(f"  - Teeth: {PINION_TEETH}")
    print(f"  - Pitch Diameter: {pinion_dims['pitch_diameter']:.2f} mm")
    print(f"  - Outer Diameter: {pinion_dims['outer_diameter']:.2f} mm")
    print(f"  - Root Diameter: {pinion_dims['root_diameter']:.2f} mm")
    
    print(f"\nCenter Distance: {center_distance:.2f} mm")
    print(f"(The pinion center is offset by this distance from the ring gear center)")
    
    if FREECAD_AVAILABLE:
        # Create or get active document
        if App.ActiveDocument is None:
            App.newDocument("InterlockingGears")
        
        doc = App.ActiveDocument
        
        # Create the gears
        print("\nCreating gears...")
        internal_gear = create_simplified_gear(
            "InternalGear", 
            internal_dims, 
            gear_type='internal',
            thickness=GEAR_THICKNESS,
            ring_wall=RING_WALL_THICKNESS
        )
        
        pinion = create_simplified_gear(
            "Pinion",
            pinion_dims,
            gear_type='external',
            thickness=GEAR_THICKNESS
        )
        
        # Position the gears
        print("Positioning gears...")
        position_gears(internal_gear, pinion, center_distance)
        
        # Recompute the document
        doc.recompute()
        
        print("\nGears created successfully!")
        print("The pinion is positioned inside the internal gear.")
    
    # Show rotation relationship
    create_rotation_animation_link(
        None, None, 
        INTERNAL_GEAR_TEETH, 
        PINION_TEETH
    )
    
    print("\n" + "=" * 60)
    print("USAGE INSTRUCTIONS")
    print("=" * 60)
    print("""
To make the gears rotate together in FreeCAD:

METHOD 1: Manual Rotation
1. Select the pinion in the model tree
2. In View -> Transform, rotate around Z axis
3. For proper meshing, rotate the internal gear by:
   rotation_angle × (pinion_teeth / internal_teeth)

METHOD 2: Using Spreadsheet (Recommended for Animation)
1. Create a new Spreadsheet (Insert -> Spreadsheet)
2. In cell A1, enter the pinion rotation angle (e.g., 45)
3. In cell B1, enter formula: =A1 * """ + f"{PINION_TEETH}/{INTERNAL_GEAR_TEETH}" + """
4. Bind Pinion rotation to A1
5. Bind InternalGear rotation to B1
6. Change A1 to animate both gears

METHOD 3: Using FreeCAD's FCGear Workbench
For more accurate gear generation:
1. Install FCGear workbench via Addon Manager
2. Create an Internal Involute Gear
3. Create an Involute Gear (pinion)
4. Position them with calculated center distance

IMPORTANT: Both gears rotate in the SAME direction when using
internal gear configuration (unlike external gears).
""")
    print("=" * 60 + "\n")


